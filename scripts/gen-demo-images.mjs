// Generates abstract, text-free SVG artwork for the demonstration articles.
// Run: node scripts/gen-demo-images.mjs   (writes client/public/demo/img-NN.svg and client/src/demo/imageManifest.js)
import fs from 'node:fs';
import path from 'node:path';

const outDir = path.resolve('client/public/demo');
fs.mkdirSync(outDir, { recursive: true });
const rng = (seed) => () => ((seed = (seed + 0x6d2b79f5) | 0), (((t) => ((t = Math.imul(t ^ (t >>> 15), t | 1)), (t ^= t + Math.imul(t ^ (t >>> 7), t | 61)), ((t ^ (t >>> 14)) >>> 0) / 4294967296))(seed)));
const P = [
  ['#10243f', '#2f6fb3', '#f2c14e'], ['#17332f', '#3f8f7a', '#e9d8a6'], ['#2b1d3a', '#7a5aa6', '#f4a261'],
  ['#1d2a44', '#4c78c9', '#f7f3e8'], ['#3a1f1d', '#b5543f', '#f1e3c4'], ['#14302a', '#6aa35f', '#f4efc9'],
  ['#222831', '#5d7a8c', '#e8c547'], ['#11273a', '#2a9d8f', '#fbe9d0'],
];
const motifs = {
  ridges: (r, [a, b, c]) => `<circle cx="${1100 + r() * 300}" cy="${230 + r() * 80}" r="${90 + r() * 40}" fill="${c}"/>` +
    [0, 1, 2, 3].map((i) => { const y = 520 + i * 120; let d = `M0 1000 L0 ${y}`; for (let x = 0; x <= 1600; x += 160) d += ` L${x} ${y - 80 - r() * 160}`; return `<path d="${d} L1600 1000Z" fill="${b}" opacity="${0.35 + i * 0.2}"/>`; }).join(''),
  arcs: (r, [a, b, c]) => [0, 1, 2, 3, 4, 5].map((i) => `<circle cx="${r() > 0.5 ? 400 : 1200}" cy="1100" r="${220 + i * 130}" fill="none" stroke="${i % 2 ? c : b}" stroke-width="${18 + r() * 24}" opacity="${0.9 - i * 0.1}"/>`).join(''),
  city: (r, [a, b, c]) => { let x = 0, s = ''; while (x < 1600) { const w = 90 + r() * 140, h = 250 + r() * 520; s += `<rect x="${x}" y="${1000 - h}" width="${w - 8}" height="${h}" fill="${r() > 0.7 ? c : b}" opacity="${0.5 + r() * 0.5}"/>`; x += w; } return s; },
  waves: (r, [a, b, c]) => [0, 1, 2, 3, 4, 5, 6].map((i) => { const y = 280 + i * 100; let d = `M0 ${y}`; for (let x = 0; x < 1600; x += 200) d += ` q100 ${-60 - r() * 50} 200 0`; return `<path d="${d}" fill="none" stroke="${i % 3 ? b : c}" stroke-width="${10 + r() * 14}" opacity="0.85"/>`; }).join(''),
  dots: (r, [a, b, c]) => Array.from({ length: 140 }, () => `<circle cx="${r() * 1600}" cy="${r() * 1000}" r="${6 + r() * 38}" fill="${r() > 0.8 ? c : b}" opacity="${0.25 + r() * 0.6}"/>`).join(''),
  bands: (r, [a, b, c]) => Array.from({ length: 9 }, (_, i) => `<polygon points="${i * 220 - 300},1000 ${i * 220 - 100},1000 ${i * 220 + 500},0 ${i * 220 + 300},0" fill="${i % 4 === 0 ? c : b}" opacity="${0.18 + r() * 0.5}"/>`).join(''),
  orbits: (r, [a, b, c]) => [1, 2, 3, 4].map((i) => `<ellipse cx="800" cy="500" rx="${180 + i * 170}" ry="${90 + i * 70}" fill="none" stroke="${b}" stroke-width="6" opacity="0.7" transform="rotate(${-18 + i * 9} 800 500)"/>`).join('') + `<circle cx="800" cy="500" r="70" fill="${c}"/><circle cx="${1150 + r() * 200}" cy="${220 + r() * 100}" r="26" fill="${c}"/>`,
  leaves: (r, [a, b, c]) => Array.from({ length: 16 }, (_, i) => `<path d="M800 1050 Q${200 + i * 80} ${250 + r() * 300} ${100 + i * 95} ${100 + r() * 200}" fill="none" stroke="${i % 5 === 0 ? c : b}" stroke-width="${8 + r() * 10}" stroke-linecap="round" opacity="0.8"/>`).join(''),
};
const names = Object.keys(motifs);
const alts = {
  ridges: 'Abstract illustration of layered hills under a pale sun',
  arcs: 'Abstract illustration of concentric arcs rising from the bottom edge',
  city: 'Abstract illustration of a skyline made of tall rectangles',
  waves: 'Abstract illustration of flowing horizontal waves',
  dots: 'Abstract illustration of scattered circles of different sizes',
  bands: 'Abstract illustration of diagonal bands of colour',
  orbits: 'Abstract illustration of overlapping orbits around a bright centre',
  leaves: 'Abstract illustration of curved stems fanning upward',
};
const manifest = [];
for (let i = 1; i <= 22; i++) {
  const motif = names[(i * 3) % names.length];
  const pal = P[(i * 5) % P.length];
  const r = rng(i * 7919);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1600 1000" width="1600" height="1000" preserveAspectRatio="xMidYMid slice"><rect width="1600" height="1000" fill="${pal[0]}"/>${motifs[motif](r, pal)}</svg>`;
  fs.writeFileSync(path.join(outDir, `img-${String(i).padStart(2, '0')}.svg`), svg);
  manifest.push(alts[motif]);
}
fs.writeFileSync('client/src/demo/imageManifest.js', `// Generated by scripts/gen-demo-images.mjs\nexport const DEMO_IMAGE_ALTS = ${JSON.stringify(manifest, null, 2)};\n`);
fs.writeFileSync('client/public/favicon.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="4" fill="#1a1c20"/><path d="M9 24V9l14 15V9" fill="none" stroke="#fbfbf9" stroke-width="3" stroke-linejoin="round"/><path d="M23 4l3.5 6h-7z" fill="#1b44c8"/></svg>`);
console.log('wrote', manifest.length, 'images');
